"""Builds ai-worker/worker.js: a Cloudflare Worker that answers chat questions the playbook can't,
grounded in the same Q&As (tools/faq_kb.py). Deploy it with your own Anthropic API key (see ai-worker/README.md)."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / 'tools'))
from faq_kb import KB
facts = '\n'.join(f'Q: {q}\nA: {re.sub("<[^>]+>", "", a)}' for _, q, a, _, _ in KB)
SYSTEM = f"""You are "Tutee Assistant", the chat assistant on Tutee Connect's "Study in the USA" page.
Tutee Connect is an overseas-education consultancy (offices in Chennai, India and Dubai, UAE) that helps students study in the United States: career counselling (free first consultation), English test prep, university selection, documentation, F-1 visa and mock interviews, education loans, scholarships guidance, post-landing support and family (F-2/H-4) visas.

Rules:
- Answer the visitor's question helpfully in 2-5 short sentences, plain text (you may use **bold**). Match the visitor's language.
- Use the reference answers below when relevant. For general questions about the USA, studying or student life, answer from general knowledge.
- Never promise or guarantee admission, visas, scholarships, jobs, OPT, H-1B, a Green Card or any immigration outcome; say outcomes depend on eligibility and the relevant US authorities.
- Do not invent statistics, fees, rankings, deadlines or Tutee Connect policies. If unsure or if it depends on the student's profile, say so and suggest a free counselling session.
- Immigration rules change; for visa specifics, remind them to confirm with official sources or a counsellor.
- Politely decline topics unrelated to studying, living or working in the USA, and steer back.
- Contact: +91 701-090-2329, +971 55-3799068, info@tuteeconnect.com.

Reference answers:
{facts}"""
js = """// Tutee Assistant — live AI answers for questions outside the page's playbook.
// Generated by tools/build-ai-worker.py. Secrets/vars: ANTHROPIC_API_KEY (secret), MODEL, ALLOWED_ORIGIN.
const SYSTEM = %s;

export default {
  async fetch(req, env) {
    const origin = req.headers.get('Origin') || '';
    const allowed = (env.ALLOWED_ORIGIN || '').split(',').map(s => s.trim()).filter(Boolean);
    const ok = allowed.length === 0 || allowed.includes(origin);
    const cors = { 'Access-Control-Allow-Origin': ok ? (origin || '*') : 'null', 'Access-Control-Allow-Methods': 'POST, OPTIONS', 'Access-Control-Allow-Headers': 'Content-Type', 'Vary': 'Origin' };
    if (req.method === 'OPTIONS') return new Response(null, { headers: cors });
    if (req.method !== 'POST' || !ok) return new Response('Not allowed', { status: 403, headers: cors });
    let body; try { body = await req.json(); } catch { return json({ error: 'bad json' }, 400, cors); }
    const q = String(body.question || '').slice(0, 300).trim();
    if (!q) return json({ error: 'empty' }, 400, cors);
    const hist = Array.isArray(body.history) ? body.history.slice(-6) : [];
    const messages = [];
    for (const h of hist) { if (h && h.q && h.a) { messages.push({ role: 'user', content: String(h.q).slice(0, 300) }); messages.push({ role: 'assistant', content: String(h.a).slice(0, 800) }); } }
    messages.push({ role: 'user', content: q });
    const r = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01' },
      body: JSON.stringify({ model: env.MODEL, max_tokens: 400, system: SYSTEM, messages })
    });
    if (!r.ok) return json({ error: 'upstream ' + r.status }, 502, cors);
    const data = await r.json();
    const answer = (data.content || []).filter(c => c.type === 'text').map(c => c.text).join('\\n').trim();
    return json({ answer }, 200, cors);
  }
};
function json(o, status, cors) { return new Response(JSON.stringify(o), { status, headers: { ...cors, 'content-type': 'application/json' } }); }
""" % json.dumps(SYSTEM)
(root / 'ai-worker' / 'worker.js').write_text(js)
print('ai-worker/worker.js', len(js))
